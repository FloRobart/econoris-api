import { z, ZodDate, ZodNumber } from "zod";
import { AmountSchema } from "../../core/schemas/amount.schema";
import { CategoryChoiceSchema, ResolvedCategorySchema } from "../categories/categories.schema";



/*========*/
/* SELECT */
/*========*/
export const OperationsSchema = z.object({
    id: z.int().min(1),
    levy_date: z.date().default(new Date()),
    label: z.string().trim().min(1).max(255),
    amount: AmountSchema,
    category_id: ResolvedCategorySchema.shape.category_id,

    /* Deprecated: kept for the clients not yet updated, which read and send a category label */
    category: ResolvedCategorySchema.shape.category,

    source: z.string().trim().max(255).nullable().default(null),
    destination: z.string().trim().max(255).nullable().default(null),
    costs: AmountSchema.default(0.0),
    is_validate: z.boolean().default(false),

    user_id: z.int().min(1),
    subscription_id: z.int().min(1).nullable().default(null),

    created_at: z.date().readonly(),
    updated_at: z.date().readonly(),
});

/* The bounds are days ("YYYY-MM-DD") rather than dates with a time: the database compares them to levy_date
   as they are, so the result never depends on the time zone of the server */
export const OperationsPeriodSchema = z.object({
    start_date: z.iso.date().optional(),
    end_date: z.iso.date().optional(),
}).refine(
    /* Days written "YYYY-MM-DD" are in chronological order when compared as strings */
    (period) => !period.start_date || !period.end_date || period.start_date <= period.end_date,
    { message: "start_date must not be after end_date" },
);

export const OperationsOldestDateSchema = z.object({
    oldest_levy_date: z.iso.date(),
});



/*========*/
/* INSERT */
/*========*/
export const OperationsInsertSchema = OperationsSchema.extend({
    user_id: OperationsSchema.shape.user_id.optional(),
    levy_date: z.preprocess<unknown, ZodDate>(
        (val) => typeof val === "string" ? new Date(val) : val,
        z.date(),
    ),

    /* The server finds the category from the choice of the client (see resolveCategory) */
    category_id: CategoryChoiceSchema.shape.category_id,
    category: CategoryChoiceSchema.shape.category,
}).omit({
    id: true,

    /* A client cannot link an operation to a subscription: nothing would check that this subscription is its own */
    subscription_id: true,

    created_at: true,
    updated_at: true,
});

/* Operations generated by the server from a subscription: the only ones linked to a subscription */
export const OperationsGeneratedInsertSchema = OperationsInsertSchema.extend({
    user_id: OperationsSchema.shape.user_id,
    subscription_id: z.int().min(1),

    /* Copied from the subscription, whose category is already resolved */
    category_id: OperationsSchema.shape.category_id,
    category: OperationsSchema.shape.category,
});



/*========*/
/* UPDATE */
/*========*/
export const OperationsIdUpdateSchema = z.object({
    id: z.preprocess<unknown, ZodNumber>(
        (val) => typeof val === "string" ? Number(val.trim()) : val,
        z.int().min(1),
    ),
});

export const OperationsUpdateSchema = OperationsInsertSchema.extend({
    id: OperationsSchema.shape.id,
});



/*========*/
/* DELETE */
/*========*/
export const OperationsIdDeleteSchema = OperationsIdUpdateSchema;
