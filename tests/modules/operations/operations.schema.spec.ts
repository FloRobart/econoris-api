import { ZodError } from 'zod';
import { OperationsGeneratedInsertSchema, OperationsInsertSchema, OperationsPeriodSchema, OperationsUpdateSchema } from '../../../src/modules/operations/operations.schema';



/**
 * Operations schemas tests
 */
describe('Operations schemas tests', () => {
    const operationSentByClient = {
        levy_date: '2026-11-05',
        label: 'Courses',
        amount: -42.5,
        category: 'Courses',
        subscription_id: 7,
    };


    it('Ignores the subscription sent by the client when it creates an operation', () => {
        expect(OperationsInsertSchema.parse(operationSentByClient)).not.toHaveProperty('subscription_id');
    });


    it('Ignores the subscription sent by the client when it updates an operation', () => {
        expect(OperationsUpdateSchema.parse({ ...operationSentByClient, id: 3 })).not.toHaveProperty('subscription_id');
    });


    it('Keeps the subscription of an operation generated by the server', () => {
        const generatedOperation = OperationsGeneratedInsertSchema.parse({ ...operationSentByClient, category_id: 49, user_id: 42 });

        expect(generatedOperation.subscription_id).toBe(7);
    });


    it('Refuses a generated operation without subscription', () => {
        expect(() => OperationsGeneratedInsertSchema.parse({ ...operationSentByClient, category_id: 49, subscription_id: undefined, user_id: 42 })).toThrow(ZodError);
    });


    it('Refuses a generated operation without category_id', () => {
        expect(() => OperationsGeneratedInsertSchema.parse({ ...operationSentByClient, user_id: 42 })).toThrow(ZodError);
    });


    it('Accepts an operation that gives its category by category_id only', () => {
        const operation = OperationsInsertSchema.parse({ ...operationSentByClient, category: undefined, category_id: 49 });

        expect(operation.category_id).toBe(49);
        expect(operation.category).toBeUndefined();
    });


    it('Refuses a blank old category label', () => {
        expect(() => OperationsInsertSchema.parse({ ...operationSentByClient, category: '   ' })).toThrow(ZodError);
    });


    it('Refuses an amount or costs that the database cannot store', () => {
        expect(() => OperationsInsertSchema.parse({ ...operationSentByClient, amount: 10000000000 })).toThrow(ZodError);
        expect(() => OperationsInsertSchema.parse({ ...operationSentByClient, costs: 10000000000 })).toThrow(ZodError);
    });
});



/**
 * Operations period schema tests: the period asked by a client when it loads its operations.
 */
describe('Operations period schema tests', () => {
    it('Accepts a period without bound, so that the clients not yet updated still get every operation', () => {
        expect(OperationsPeriodSchema.parse({})).toEqual({});
    });


    it('Accepts a period with only one of its bounds', () => {
        expect(OperationsPeriodSchema.parse({ start_date: '2026-09-01' })).toEqual({ start_date: '2026-09-01' });
        expect(OperationsPeriodSchema.parse({ end_date: '2026-08-31' })).toEqual({ end_date: '2026-08-31' });
    });


    it('Accepts a period of a single day', () => {
        expect(OperationsPeriodSchema.parse({ start_date: '2026-09-01', end_date: '2026-09-01' })).toEqual({ start_date: '2026-09-01', end_date: '2026-09-01' });
    });


    it('Refuses a bound that is not a day "YYYY-MM-DD"', () => {
        expect(() => OperationsPeriodSchema.parse({ start_date: '01/09/2026' })).toThrow(ZodError);
        expect(() => OperationsPeriodSchema.parse({ start_date: '2026-09-01T00:00:00.000Z' })).toThrow(ZodError);
        expect(() => OperationsPeriodSchema.parse({ end_date: '2026-02-30' })).toThrow(ZodError);
    });


    it('Refuses a period that ends before it starts', () => {
        expect(() => OperationsPeriodSchema.parse({ start_date: '2026-11-30', end_date: '2026-09-01' })).toThrow(ZodError);
    });
});
