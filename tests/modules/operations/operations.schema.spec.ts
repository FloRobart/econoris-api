import { ZodError } from 'zod';
import { OperationsGeneratedInsertSchema, OperationsInsertSchema, OperationsUpdateSchema } from '../../../src/modules/operations/operations.schema';



/**
 * Operations schemas tests
 */
describe('Operations schemas tests', () => {
    const operationSentByClient = {
        levy_date: '2026-11-05',
        label: 'Courses',
        amount: -42.5,
        category: 'Courses',
        subscription_id: 7,
    };


    it('Ignores the subscription sent by the client when it creates an operation', () => {
        expect(OperationsInsertSchema.parse(operationSentByClient)).not.toHaveProperty('subscription_id');
    });


    it('Ignores the subscription sent by the client when it updates an operation', () => {
        expect(OperationsUpdateSchema.parse({ ...operationSentByClient, id: 3 })).not.toHaveProperty('subscription_id');
    });


    it('Keeps the subscription of an operation generated by the server', () => {
        const generatedOperation = OperationsGeneratedInsertSchema.parse({ ...operationSentByClient, user_id: 42 });

        expect(generatedOperation.subscription_id).toBe(7);
    });


    it('Refuses a generated operation without subscription', () => {
        expect(() => OperationsGeneratedInsertSchema.parse({ ...operationSentByClient, subscription_id: undefined, user_id: 42 })).toThrow(ZodError);
    });
});
